"""陪伴旅程的固定关卡规则；奖励只依赖有效监测时间。"""

GOALS = (15, 20, 25, 20, 25, 20, 15)
STATIONS = (
    ("晨光", "从一个短时段开始，找回自己的节奏。"),
    ("书桌", "把一点点专注，留给今天想做的事。"),
    ("林间", "走得稳一些，也记得看看窗外。"),
    ("石桥", "走过一半，给自己留一点休息时间。"),
    ("山坡", "今天的脚步，已经比昨天更远。"),
    ("灯塔", "看见自己的节奏，再向前一点。"),
    ("星空", "旅程告一段落，明天仍能从容出发。"),
)


def station_for(completions):
    """返回从 1 开始的旅程轮次、站点和分钟目标。"""
    return completions // len(GOALS) + 1, completions % len(GOALS) + 1, GOALS[completions % len(GOALS)]
